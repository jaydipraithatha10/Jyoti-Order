// ==============================
// Read CSV
// ==============================

async function fetchCSV(url) {

    const response = await fetch(url);
    const text = await response.text();

    return text;

}


// ==============================
// CSV to Array
// ==============================

function csvToArray(csv) {

    const rows = csv.trim().split("\n");

    return rows.map(row => row.split(","));

}